-- Temacase v59 - allegati delle notizie (PDF/Word/Excel/foto).
-- Non copia file binari: conserva file_id Telegram e metadati verificati dal bot.
-- Nessuna modifica né cancellazione di notizie o fotografie precedenti.
BEGIN;
CREATE TABLE IF NOT EXISTS temacase_test.crm_allegati_notizie (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 notizia_id bigint NOT NULL REFERENCES temacase_test.notizie_acquisizione(id) ON DELETE CASCADE,
 consulente_telegram_id bigint NOT NULL,
 telegram_update_id bigint NOT NULL UNIQUE,
 telegram_file_id text NOT NULL,
 nome_file text NOT NULL,
 mime_type text NOT NULL,
 tipo text NOT NULL CHECK (tipo IN ('documento','foto')),
 dimensione integer NOT NULL DEFAULT 0 CHECK (dimensione BETWEEN 0 AND 20000000),
 creato_il timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT crm_allegati_file_id_v59_check CHECK (char_length(btrim(telegram_file_id)) BETWEEN 8 AND 1024),
 CONSTRAINT crm_allegati_nome_v59_check CHECK (char_length(btrim(nome_file)) BETWEEN 1 AND 220),
 CONSTRAINT crm_allegati_mime_v59_check CHECK (mime_type IN (
 'application/pdf','application/msword','application/vnd.openxmlformats-officedocument.wordprocessingml.document',
 'application/vnd.ms-excel','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
 'image/jpeg','image/png','image/webp'))
);
CREATE INDEX IF NOT EXISTS crm_allegati_notizie_consulente_v59
 ON temacase_test.crm_allegati_notizie(consulente_telegram_id,notizia_id,id DESC);
ALTER TABLE temacase_test.crm_allegati_notizie ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='temacase_test'
     AND tablename='crm_allegati_notizie' AND policyname='crm_allegati_notizie_personali_v59') THEN
   CREATE POLICY crm_allegati_notizie_personali_v59 ON temacase_test.crm_allegati_notizie
    FOR ALL TO PUBLIC
    USING (
     consulente_telegram_id = NULLIF(current_setting('temacase.telegram_user_id', true),'')::bigint
     AND EXISTS (SELECT 1 FROM temacase_test.notizie_acquisizione n
       WHERE n.id=crm_allegati_notizie.notizia_id AND n.consulente_telegram_id=crm_allegati_notizie.consulente_telegram_id)
    )
    WITH CHECK (
     consulente_telegram_id = NULLIF(current_setting('temacase.telegram_user_id', true),'')::bigint
     AND EXISTS (SELECT 1 FROM temacase_test.notizie_acquisizione n
       WHERE n.id=crm_allegati_notizie.notizia_id AND n.consulente_telegram_id=crm_allegati_notizie.consulente_telegram_id)
    );
 END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='temacase_mcp_login') THEN
   RAISE EXCEPTION 'Ruolo temacase_mcp_login non disponibile';
 END IF;
 GRANT USAGE ON SCHEMA temacase_test TO temacase_mcp_login;
 GRANT SELECT,INSERT,DELETE ON temacase_test.crm_allegati_notizie TO temacase_mcp_login;
 GRANT USAGE,SELECT ON SEQUENCE temacase_test.crm_allegati_notizie_id_seq TO temacase_mcp_login;
END $$;
COMMIT;
SELECT to_regclass('temacase_test.crm_allegati_notizie') IS NOT NULL AS tabella_disponibile,
 has_table_privilege('temacase_mcp_login','temacase_test.crm_allegati_notizie','SELECT') AS bot_puo_leggere,
 has_table_privilege('temacase_mcp_login','temacase_test.crm_allegati_notizie','INSERT') AS bot_puo_aggiungere,
 has_table_privilege('temacase_mcp_login','temacase_test.crm_allegati_notizie','DELETE') AS bot_puo_eliminare,
 (SELECT relrowsecurity FROM pg_class WHERE oid='temacase_test.crm_allegati_notizie'::regclass) AS rls_attiva;
