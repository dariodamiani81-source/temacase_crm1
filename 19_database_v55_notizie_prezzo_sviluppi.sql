-- TEMACASE v55 - schema Notizie coerente e storico sviluppi.
-- Migrazione non distruttiva. Eseguire nel Supabase SQL Editor come postgres.
BEGIN;
ALTER TABLE temacase_test.notizie_acquisizione
  ADD COLUMN IF NOT EXISTS operazione text,
  ADD COLUMN IF NOT EXISTS prezzo_richiesto numeric(14,2);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid='temacase_test.notizie_acquisizione'::regclass
      AND conname='notizie_acquisizione_operazione_v55_check'
  ) THEN
    ALTER TABLE temacase_test.notizie_acquisizione
      ADD CONSTRAINT notizie_acquisizione_operazione_v55_check
      CHECK (operazione IS NULL OR operazione IN ('vendita','locazione'));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid='temacase_test.notizie_acquisizione'::regclass
      AND conname='notizie_acquisizione_prezzo_v55_check'
  ) THEN
    ALTER TABLE temacase_test.notizie_acquisizione
      ADD CONSTRAINT notizie_acquisizione_prezzo_v55_check
      CHECK (prezzo_richiesto IS NULL OR (prezzo_richiesto > 0 AND prezzo_richiesto <= 999999999999.99));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS temacase_test.crm_sviluppi_notizie (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notizia_id bigint NOT NULL REFERENCES temacase_test.notizie_acquisizione(id) ON DELETE CASCADE,
  consulente_telegram_id bigint NOT NULL,
  data_sviluppo date NOT NULL,
  nota text NOT NULL,
  creato_il timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT crm_sviluppi_notizie_nota_check CHECK (char_length(btrim(nota)) BETWEEN 2 AND 1200)
);
CREATE INDEX IF NOT EXISTS crm_sviluppi_notizie_lookup_v55
  ON temacase_test.crm_sviluppi_notizie(consulente_telegram_id,notizia_id,data_sviluppo DESC,id DESC);
ALTER TABLE temacase_test.crm_sviluppi_notizie ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies
                 WHERE schemaname='temacase_test'
                   AND tablename='crm_sviluppi_notizie'
                   AND policyname='crm_sviluppi_notizie_v55_personali') THEN
    CREATE POLICY crm_sviluppi_notizie_v55_personali
      ON temacase_test.crm_sviluppi_notizie FOR ALL TO PUBLIC
      USING (
        consulente_telegram_id = NULLIF(current_setting('temacase.telegram_user_id',true),'')::bigint
        AND EXISTS (SELECT 1 FROM temacase_test.notizie_acquisizione n
                    WHERE n.id=crm_sviluppi_notizie.notizia_id AND n.consulente_telegram_id=crm_sviluppi_notizie.consulente_telegram_id)
      )
      WITH CHECK (
        consulente_telegram_id = NULLIF(current_setting('temacase.telegram_user_id',true),'')::bigint
        AND EXISTS (SELECT 1 FROM temacase_test.notizie_acquisizione n
                    WHERE n.id=crm_sviluppi_notizie.notizia_id AND n.consulente_telegram_id=crm_sviluppi_notizie.consulente_telegram_id)
      );
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='temacase_mcp_login') THEN
    GRANT USAGE ON SCHEMA temacase_test TO temacase_mcp_login;
    GRANT SELECT,INSERT ON temacase_test.crm_sviluppi_notizie TO temacase_mcp_login;
    GRANT USAGE,SELECT ON SEQUENCE temacase_test.crm_sviluppi_notizie_id_seq TO temacase_mcp_login;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
    GRANT SELECT,INSERT ON temacase_test.crm_sviluppi_notizie TO service_role;
    GRANT USAGE,SELECT ON SEQUENCE temacase_test.crm_sviluppi_notizie_id_seq TO service_role;
  END IF;
END $$;
COMMIT;
SELECT
 EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='temacase_test' AND table_name='notizie_acquisizione' AND column_name='prezzo_richiesto') AS prezzo_presente,
 EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='temacase_test' AND table_name='notizie_acquisizione' AND column_name='operazione') AS operazione_presente,
 to_regclass('temacase_test.crm_sviluppi_notizie') IS NOT NULL AS storico_disponibile,
 has_table_privilege('temacase_mcp_login','temacase_test.crm_sviluppi_notizie','INSERT') AS bot_puo_registrare_sviluppi;
